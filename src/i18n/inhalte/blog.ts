// Ersetzt {schluessel} im Text durch den passenden Wert
export function fuelle(text: string, werte: Record<string, string | number>) {
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(werte[k] ?? `{${k}}`))
}

